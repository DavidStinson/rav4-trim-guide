"""Download the site's photos at full size and make the copies the page uses.

    python3 tools/build_photos.py

rav4-cfg/photos.json lists every photo: a Toyota build-tool render (`render`, a path under the `scene7`
host, read from the build tool for the 2027 models), a Toyota press photo (`url`), or a saved file (`file`).
Each photo's `kind` sets its crop and its page width. Crops are in the build tool's 900px-wide frame and
scale with the source, so they cut the same spot at any size.

For each photo this writes three WebP copies to rav4-site/img/:
    <name>.webp        the page copy, `width` px wide
    <name>@2x.webp     twice that, for sharp screens (or the full size, if the source is smaller)
    full/<name>.webp   the whole source after cropping, for the expanded view
and writes their widths and heights to rav4-site/photos.js. The page reads it to build each photo's srcset
and its width and height attributes, which hold the photo's shape before the file loads.

Downloads are cached in rav4-cfg/originals/ (not committed; they're large). Re-running skips cached
downloads. Needs curl and ImageMagick (`magick`).
"""
import json, pathlib, subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
MANIFEST = ROOT / 'rav4-cfg' / 'photos.json'
CACHE = ROOT / 'rav4-cfg' / 'originals'
IMG = ROOT / 'rav4-site' / 'img'
JS = ROOT / 'rav4-site' / 'photos.js'
RENDER_WIDTH = 4000  # The largest size Toyota's image server sends.
FRAME = 900          # Crops are written in this frame's pixels.


def fetch(url, dest):
    if dest.exists():
        return
    tmp = dest.with_suffix('.part')
    kind = subprocess.run(['curl', '-sSfL', '--retry', '3', '--max-time', '180', '-o', str(tmp), '-w', '%{content_type}', url],
                          check=True, capture_output=True, text=True).stdout
    if not kind.startswith('image/'):
        tmp.unlink(missing_ok=True)
        raise SystemExit(f'unexpected response for {dest.name}: {kind}')
    tmp.rename(dest)


def size(path):
    w, h = subprocess.run(['magick', 'identify', '-format', '%w %h', f'{path}[0]'], check=True, capture_output=True, text=True).stdout.split()
    return int(w), int(h)


def source(p, kind, scene7):
    """Return the cached original for a photo, downloading it if needed."""
    if 'file' in p:
        return ROOT / p['file']
    alpha = kind.get('alpha', False)
    ext = 'png' if alpha or 'url' in p else 'jpg'
    raw = CACHE / f'{p["name"].replace("/", "_")}.{ext}'
    if 'render' in p:
        fmt = 'png-alpha' if alpha else 'jpg&qlt=95'
        fetch(f'{scene7}{p["render"]}.png?wid={RENDER_WIDTH}&fmt={fmt}', raw)
    else:
        fetch(p['url'], raw)  # Toyota's press photo server sends the original when no width is asked for.
    return raw


def main():
    man = json.loads(MANIFEST.read_text())
    CACHE.mkdir(parents=True, exist_ok=True)
    photos = {}
    for p in man['photos']:
        kind = man['kinds'][p['kind']]
        raw = source(p, kind, man['scene7'])
        sw, sh = size(raw)
        ops = []
        if 'crop' in kind:
            x, y, w, h = (round(v * sw / FRAME) for v in kind['crop'])
            ops += ['-crop', f'{w}x{h}+{x}+{y}', '+repage']
        if 'brighten' in p:  # Lift the lightness only, so the colors don't shift.
            ops += ['-colorspace', 'Lab', '-channel', 'R', '-gamma', str(p['brighten']), '+channel', '-colorspace', 'sRGB']
        quality = ['-quality', '82', '-define', 'webp:method=6']
        if kind.get('alpha'):
            quality += ['-define', 'webp:alpha-quality=90']
        else:
            ops += ['-alpha', 'off']
        full = IMG / 'full' / f'{p["name"]}.webp'
        full.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(['magick', str(raw), *ops, *quality, str(full)], check=True)
        fw, fh = size(full)
        w1 = min(kind['width'], fw)
        w2 = min(2 * w1, fw)
        heights = []
        for w, out in ((w1, IMG / f'{p["name"]}.webp'), (w2, IMG / f'{p["name"]}@2x.webp')):
            out.parent.mkdir(parents=True, exist_ok=True)
            subprocess.run(['magick', str(full), '-resize', f'{w}x', *quality, str(out)], check=True)
            heights.append(size(out)[1])  # Read back, since the resize rounds the height.
        photos[p['name']] = {'widths': [w1, w2, fw], 'heights': [*heights, fh]}
        print(p['name'], photos[p['name']])
    lines = ',\n'.join(f'{json.dumps(name)}: {json.dumps(v)}' for name, v in photos.items())
    JS.write_text(
        '// Generated by tools/build_photos.py. Each photo\'s copies in px, in order: page copy, 2x copy, full size.\n'
        'window.PHOTOS = {\n' + lines + '\n};\n')


if __name__ == '__main__':
    main()
